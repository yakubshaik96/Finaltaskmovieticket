export const movies = [
  ...released.map((movie) => ({ ...movie, status: "now-showing" })),
  ...upcoming.map((movie) => ({ ...movie, status: "coming-soon" })),
]

export const nowShowing = movies.filter((movie) => movie.status === "now-showing")
export const comingSoon = movies.filter((movie) => movie.status === "coming-soon")

export function isBookable(movie) {
  return Boolean(movie) && movie.status === "now-showing"
}

export function getMovie(id) {
  return movies.find((movie) => movie.id === id)
}

export const genres = [...new Set(movies.flatMap((movie) => movie.genres))]
export const languages = [...new Set(movies.flatMap((movie) => movie.languages))]
